#!/usr/bin/env node
// Regenerates every artifact this crate takes from upstream gpu-lexer, so no
// weight, scale or shader is ever copied by hand:
//
//   model/weights-int6-active.bin     the promoted int6 checkpoint (CPU backend)
//   model/model-active.json           its metadata, kept for provenance
//   model/runtime-weights.txt         the runtime weight symbols (GPU backend)
//   model/shader-f16.wgsl             the promoted WGSL shader, f16 storage
//   model/shader-f32.wgsl             the same shader with f32 storage
//   src/generated/model.rs            tensor table, scales and dimensions
//   src/generated/runtime.rs          runtime weight ranges and entry points
//   js/gpu-lexer.js                   the published npm bundle plus a bridge
//
// Usage:
//   node scripts/sync-upstream.mjs <gpu-lexer checkout> <gpu-lexer-0.0.6.tgz extracted dir>
//
// scripts/fetch-upstream.sh fetches both at the pinned commit and version.

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const UPSTREAM_COMMIT = "676026856660a22567345014835867a9dfe3fbdb";
export const UPSTREAM_VERSION = "0.0.6";
export const UPSTREAM_NPM_INTEGRITY =
  "sha512-hL0WzAtwijM3sdBsGqdEZuknwXCIup9c74YAQ/QTrQv/MQQZXUEcwr47u1fNmF6EysWPsD41jEFhMrQs1gI2PQ==";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const [upstreamArg, npmArg] = process.argv.slice(2);
if (!upstreamArg || !npmArg) {
  console.error("usage: node scripts/sync-upstream.mjs <gpu-lexer checkout> <npm package dir>");
  process.exit(2);
}
const upstream = resolve(upstreamArg);
const npmDir = resolve(npmArg);

const corePackage = JSON.parse(readFileSync(join(upstream, "packages/core/package.json"), "utf8"));
if (corePackage.version !== UPSTREAM_VERSION) {
  throw new Error(`upstream checkout is gpu-lexer ${corePackage.version}, expected ${UPSTREAM_VERSION}`);
}
const npmPackage = JSON.parse(readFileSync(join(npmDir, "package.json"), "utf8"));
if (npmPackage.name !== "gpu-lexer" || npmPackage.version !== UPSTREAM_VERSION) {
  throw new Error(`npm package is ${npmPackage.name}@${npmPackage.version}, expected gpu-lexer@${UPSTREAM_VERSION}`);
}

const active = join(upstream, "packages/training/active");
const metadata = JSON.parse(readFileSync(join(active, "model-active.json"), "utf8"));
const int6 = readFileSync(join(active, "weights-int6-active.bin"));
const { promotedRunId } = await import(pathToFileURL(join(upstream, "packages/training/src/promoted-run.generated.js")));
if (metadata.runId !== promotedRunId) {
  throw new Error(`active checkpoint ${metadata.runId} is not the promoted run ${promotedRunId}`);
}

// The CPU forward pass below is the exact format-9 hybrid tree of tree-model.js.
const expect = (condition, message) => { if (!condition) throw new Error(`unsupported checkpoint: ${message}`); };
expect(metadata.model === "hierarchical-tree" && metadata.formatVersion === 9, "format");
expect(metadata.featureVersion === 3 && metadata.tokenizerVersion === 2, "feature/tokenizer version");
expect(metadata.architecture.context === "local-affine-tree" && metadata.architecture.localRadius === 2, "context");
expect(metadata.architecture.lexemeHashBuckets === 256, "hash buckets");
expect(metadata.architecture.scaleBuckets === 12, "scale buckets");
expect(metadata.hiddenSize === 32, "hidden size");
expect(metadata.inputSize === 755, "input size");
expect(metadata.quantization.bits === 6, "int6");
expect(int6.length === metadata.quantization.packedByteLength, "packed length");
expect(JSON.stringify(metadata.classNames) ===
  JSON.stringify(["plain", "comment", "string", "number", "keyword", "type", "function", "constant", "operator"]), "class order");

const shapes = Object.fromEntries(metadata.tensorLayout.map((tensor) => [tensor.name, tensor.shape]));
const tensors = metadata.quantization.tensors;
let offset = 0;
for (const tensor of tensors) {
  expect(tensor.offset === offset && tensor.length > 0 && tensor.scale > 0, `tensor ${tensor.name} layout`);
  offset += tensor.length;
}
expect(offset === metadata.quantization.parameterCount, "parameter count");

const rustIdent = (name) => name.replace(/[A-Z]/g, (c) => `_${c}`).toUpperCase();
// JS prints the shortest decimal that round-trips a double; Rust parses it to the same double.
const f64 = (value) => {
  const text = String(value);
  return /[.e]/.test(text) ? text : `${text}.0`;
};

const digest = (bytes) => createHash("sha256").update(bytes).digest("hex");
const generatedHeader = (what) =>
  `// @generated by scripts/sync-upstream.mjs from gpu-lexer ${UPSTREAM_VERSION}\n` +
  `// (commit ${UPSTREAM_COMMIT}, checkpoint ${metadata.runId}). ${what}\n` +
  "// Do not edit by hand: run the script again.\n\n";

mkdirSync(join(root, "model"), { recursive: true });
mkdirSync(join(root, "src/generated"), { recursive: true });
mkdirSync(join(root, "js"), { recursive: true });
copyFileSync(join(active, "weights-int6-active.bin"), join(root, "model/weights-int6-active.bin"));
copyFileSync(join(active, "model-active.json"), join(root, "model/model-active.json"));

let model = generatedHeader("The promoted int6 checkpoint the CPU backend runs.");
model += `/// The upstream gpu-lexer version the weights come from.\npub const UPSTREAM_VERSION: &str = "${UPSTREAM_VERSION}";\n`;
model += `/// The upstream commit the weights come from.\npub const UPSTREAM_COMMIT: &str = "${UPSTREAM_COMMIT}";\n`;
model += `/// The promoted checkpoint's run id.\npub const RUN_ID: &str = "${metadata.runId}";\n`;
model += `/// SHA-256 of \`model/weights-int6-active.bin\`.\npub const WEIGHTS_SHA256: &str = "${digest(int6)}";\n`;
model += `pub const HIDDEN: usize = ${metadata.hiddenSize};\n`;
model += `pub const INPUT_SIZE: usize = ${metadata.inputSize};\n`;
model += `pub const CLASSIFIER: usize = ${metadata.architecture.classifierDimensions};\n`;
model += `pub const AUXILIARY: usize = ${metadata.auxiliaryNames.length};\n`;
model += `pub const CLASSES: usize = ${metadata.classNames.length};\n`;
model += `pub const SCALE_BUCKETS: usize = ${metadata.architecture.scaleBuckets};\n`;
model += `pub const PARAMETER_COUNT: usize = ${metadata.quantization.parameterCount};\n`;
model += `pub const WEIGHT_BITS: u32 = ${metadata.quantization.bits};\n\n`;
model += "/// The packed signed int6 codes of every tensor, in `TENSORS` order.\n";
model += "pub static WEIGHTS_INT6: &[u8] = include_bytes!(\"../../model/weights-int6-active.bin\");\n\n";
model += "/// One tensor of the checkpoint: its codes are `offset..offset + length`.\n";
model += "#[derive(Debug, Clone, Copy)]\npub struct TensorSpec {\n    pub name: &'static str,\n    pub offset: usize,\n    pub length: usize,\n    pub scale: f64,\n    pub shape: &'static [usize],\n}\n\n";
for (const tensor of tensors) {
  model += `pub const ${rustIdent(tensor.name)}: TensorSpec = TensorSpec { name: "${tensor.name}", offset: ${tensor.offset}, length: ${tensor.length}, scale: ${f64(tensor.scale)}, shape: &[${shapes[tensor.name].join(", ")}] };\n`;
}
model += `\npub const TENSORS: [TensorSpec; ${tensors.length}] = [${tensors.map((t) => rustIdent(t.name)).join(", ")}];\n`;
writeFileSync(join(root, "src/generated/model.rs"), model);

// The one change made to upstream's shader. `tree_down_classify` writes each
// child's returned context over its upward state in workgroup memory while
// the threads of partner channels (h ^ 1 << depth) may still be reading that
// upward state. Where a block's 32 channels run as one lockstep SIMD group
// (Apple GPUs) the race is benign; on 8- or 16-wide hardware (llvmpipe,
// many Intel and mobile GPUs) it changed 0.8% of three.min.js's labels.
// The fix computes a level's children first and writes them after a barrier,
// which is what the JS reference computes.
const DOWN_RACE = "{for(var Ba=rb;Ba<y;Ba+=2u){let E=Ba*2u;if (E>=Sd){continue;}let qc=q[(Qd+Ba)*32u+p];let Td=q[(Q+E)*32u+p];if (E+1u<Sd){let Ud=q[(Q+E+1u)*32u+p];let rc=p^(1u<<A);let Vd=q[(Qd+Ba)*32u+rc];let Wd=q[(Q+E)*32u+rc];let Xd=q[(Q+E+1u)*32u+rc];q[(Q+E)*32u+p]=Ha(qc,Td,Ud,Vd,Wd,Xd,p,A,false);q[(Q+E+1u)*32u+p]=Ha(qc,Ud,Td,Vd,Xd,Wd,p,A,true);} else{q[(Q+E)*32u+p]=qc;}}}workgroupBarrier();";
const DOWN_FIXED = "{var nshL:array<f32,8>;var nshR:array<f32,8>;var nshK=0u;for(var Ba=rb;Ba<y;Ba+=2u){let E=Ba*2u;if (E>=Sd){continue;}let qc=q[(Qd+Ba)*32u+p];let Td=q[(Q+E)*32u+p];if (E+1u<Sd){let Ud=q[(Q+E+1u)*32u+p];let rc=p^(1u<<A);let Vd=q[(Qd+Ba)*32u+rc];let Wd=q[(Q+E)*32u+rc];let Xd=q[(Q+E+1u)*32u+rc];nshL[nshK]=Ha(qc,Td,Ud,Vd,Wd,Xd,p,A,false);nshR[nshK]=Ha(qc,Ud,Td,Vd,Xd,Wd,p,A,true);} else{nshL[nshK]=qc;}nshK+=1u;}workgroupBarrier();nshK=0u;for(var Ba=rb;Ba<y;Ba+=2u){let E=Ba*2u;if (E>=Sd){continue;}q[(Q+E)*32u+p]=nshL[nshK];if (E+1u<Sd){q[(Q+E+1u)*32u+p]=nshR[nshK];}nshK+=1u;}}workgroupBarrier();";
const fixDownRace = (text, where) => {
  const count = text.split(DOWN_RACE).length - 1;
  if (count !== 1) throw new Error(`${where}: expected the in-block down pass once, found ${count}; review the patch`);
  return text.replace(DOWN_RACE, DOWN_FIXED);
};

// GPU artifacts: what the npm package's runtime uploads and compiles.
const runtimeModel = await import(pathToFileURL(join(upstream, "packages/core/src/model.runtime.generated.js")));
const shaderModule = await import(pathToFileURL(join(upstream, "packages/core/src/shader.min.generated.js")));
writeFileSync(join(root, "model/runtime-weights.txt"), runtimeModel.WEIGHTS);
writeFileSync(join(root, "model/shader-f16.wgsl"), fixDownRace(shaderModule.createPromotedShader(true), "f16 shader") + "\n");
writeFileSync(join(root, "model/shader-f32.wgsl"), fixDownRace(shaderModule.createPromotedShader(false), "f32 shader") + "\n");
let runtime = generatedHeader("The runtime weights and shader the GPU backend uploads.");
runtime += `pub const HIDDEN: usize = ${runtimeModel.HIDDEN_SIZE};\n`;
runtime += `pub const WEIGHT_BITS: u32 = ${runtimeModel.WEIGHT_BITS};\n`;
runtime += `/// Pairs of (length, scale) over \`WEIGHTS\`, as \`weights.js\` reads them.\n`;
runtime += `pub const WEIGHT_RANGES: [(usize, f64); ${runtimeModel.WEIGHT_RANGES.length / 2}] = [\n`;
for (let index = 0; index < runtimeModel.WEIGHT_RANGES.length; index += 2) {
  runtime += `    (${runtimeModel.WEIGHT_RANGES[index]}, ${f64(runtimeModel.WEIGHT_RANGES[index + 1])}),\n`;
}
runtime += "];\n";
runtime += "/// One symbol per weight, in the runtime buffer order.\n";
runtime += "pub static WEIGHTS: &str = include_str!(\"../../model/runtime-weights.txt\");\n";
runtime += `/// The compute entry points, one per pipeline, in dispatch order.\npub const ENTRY_POINTS: &str = "${shaderModule.TREE_ENTRY_POINTS}";\n`;
runtime += "pub static SHADER_F16: &str = include_str!(\"../../model/shader-f16.wgsl\");\n";
runtime += "pub static SHADER_F32: &str = include_str!(\"../../model/shader-f32.wgsl\");\n";
writeFileSync(join(root, "src/generated/runtime.rs"), runtime);

// Web: the published bundle, with the same shader fix and a bridge wasm-bindgen imports.
const bundle = fixDownRace(readFileSync(join(npmDir, "dist/index.js"), "utf8"), "npm bundle");
const bridge = `
// ---- nsh-gpu-lexer bridge (appended by scripts/sync-upstream.mjs) ----
// gpu-lexer ${UPSTREAM_VERSION} (${UPSTREAM_NPM_INTEGRITY}), MIT, Copyright (c) 2026 Shu Ding.
const nshClassCodes = { plain: 0, comment: 1, string: 2, number: 3, keyword: 4, type: 5, function: 6, constant: 7, operator: 8 };
export function nshGpuLexerAvailable() {
  return typeof navigator !== "undefined" && !!navigator.gpu;
}
// Resolves to a Uint32Array of [class, start, end, confidence * 16] per span.
export async function nshGpuLexerParse(code) {
  const spans = await parse(code);
  const out = new Uint32Array(spans.length * 4);
  for (let index = 0; index < spans.length; index++) {
    const span = spans[index];
    out[index * 4] = nshClassCodes[span.type] ?? 0;
    out[index * 4 + 1] = span.start;
    out[index * 4 + 2] = span.end;
    out[index * 4 + 3] = Math.round(span.confidence * 16);
  }
  return out;
}
`;
writeFileSync(join(root, "js/gpu-lexer.js"),
  `// gpu-lexer@${UPSTREAM_VERSION} dist/index.js, MIT License, Copyright (c) 2026 Shu Ding.\n` +
  `// Vendored by scripts/sync-upstream.mjs with one fix to its shader (the in-block\n` +
  `// top-down race, see the script) and the bridge at the end.\n` +
  bundle + bridge);

console.log(`synced gpu-lexer ${UPSTREAM_VERSION} checkpoint ${metadata.runId}: ${tensors.length} tensors, ` +
  `${metadata.quantization.parameterCount} parameters, int6 sha256 ${digest(int6)}`);
